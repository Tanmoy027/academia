-- Assignments Table
-- This table stores assignments created by teachers for their courses

CREATE TABLE IF NOT EXISTS assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(500) NOT NULL,
    description TEXT NULL,
    due_date TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    max_points INTEGER DEFAULT 100,
    attachment_url VARCHAR(500) NULL,
    is_published BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NULL
);

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS assignments_course_id_index ON assignments(course_id);
CREATE INDEX IF NOT EXISTS assignments_teacher_id_index ON assignments(teacher_id);
CREATE INDEX IF NOT EXISTS assignments_due_date_index ON assignments(due_date);
CREATE INDEX IF NOT EXISTS assignments_is_published_index ON assignments(is_published);

-- Add comments for documentation
COMMENT ON TABLE assignments IS 'Stores assignments created by teachers for their courses';
COMMENT ON COLUMN assignments.course_id IS 'The course this assignment belongs to';
COMMENT ON COLUMN assignments.teacher_id IS 'The teacher who created this assignment';
COMMENT ON COLUMN assignments.title IS 'Assignment title';
COMMENT ON COLUMN assignments.description IS 'Detailed assignment description and instructions';
COMMENT ON COLUMN assignments.due_date IS 'Assignment due date and time';
COMMENT ON COLUMN assignments.max_points IS 'Maximum points/marks for this assignment';
COMMENT ON COLUMN assignments.attachment_url IS 'URL to attachment file (PDF, docs, etc.)';
COMMENT ON COLUMN assignments.is_published IS 'Whether the assignment is visible to students';
