-- ============================================
-- TEACHER SALARY PAYMENTS SCHEMA FOR SUPABASE
-- Run this SQL in Supabase SQL Editor
-- ============================================

-- Create teacher_salaries table
CREATE TABLE IF NOT EXISTS teacher_salaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    amount DECIMAL(10, 2) NOT NULL,
    month INTEGER NOT NULL CHECK (month >= 1 AND month <= 12),
    year INTEGER NOT NULL,
    description TEXT NULL,
    transaction_id VARCHAR(255) NULL,
    stripe_transfer_id VARCHAR(255) NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'pending',
    payment_method VARCHAR(50) DEFAULT 'stripe',
    paid_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    paid_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Add Stripe Connect account ID to users table for teachers
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name = 'users' AND column_name = 'stripe_connect_id'
    ) THEN
        ALTER TABLE users ADD COLUMN stripe_connect_id VARCHAR(255) NULL;
    END IF;
    
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name = 'users' AND column_name = 'stripe_account_status'
    ) THEN
        ALTER TABLE users ADD COLUMN stripe_account_status VARCHAR(50) DEFAULT 'not_connected';
    END IF;
    
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name = 'users' AND column_name = 'base_salary'
    ) THEN
        ALTER TABLE users ADD COLUMN base_salary DECIMAL(10, 2) DEFAULT 0.00;
    END IF;
END $$;

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS idx_teacher_salaries_teacher_id ON teacher_salaries(teacher_id);
CREATE INDEX IF NOT EXISTS idx_teacher_salaries_status ON teacher_salaries(status);
CREATE INDEX IF NOT EXISTS idx_teacher_salaries_month_year ON teacher_salaries(month, year);
CREATE INDEX IF NOT EXISTS idx_teacher_salaries_paid_at ON teacher_salaries(paid_at);
CREATE INDEX IF NOT EXISTS idx_users_stripe_connect_id ON users(stripe_connect_id);

-- Enable RLS on teacher_salaries table
ALTER TABLE teacher_salaries ENABLE ROW LEVEL SECURITY;

-- Policy for admins to manage all salary records
DROP POLICY IF EXISTS "Admins can manage all salaries" ON teacher_salaries;
CREATE POLICY "Admins can manage all salaries" ON teacher_salaries
    FOR ALL
    USING (true);

-- Policy for teachers to view their own salary records
DROP POLICY IF EXISTS "Teachers can view own salaries" ON teacher_salaries;
CREATE POLICY "Teachers can view own salaries" ON teacher_salaries
    FOR SELECT
    USING (auth.uid()::text = teacher_id::text);

SELECT 'Teacher salaries table created successfully!' as result;
