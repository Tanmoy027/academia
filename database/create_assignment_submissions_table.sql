-- Assignment Submissions Table
-- This table stores student submissions for assignments

CREATE TABLE IF NOT EXISTS assignment_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    submission_text TEXT NULL,
    attachment_url VARCHAR(500) NULL,
    submitted_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    grade INTEGER NULL,
    feedback TEXT NULL,
    graded_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    graded_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    UNIQUE(assignment_id, user_id)
);

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS assignment_submissions_assignment_id_index ON assignment_submissions(assignment_id);
CREATE INDEX IF NOT EXISTS assignment_submissions_user_id_index ON assignment_submissions(user_id);
CREATE INDEX IF NOT EXISTS assignment_submissions_submitted_at_index ON assignment_submissions(submitted_at);
CREATE INDEX IF NOT EXISTS assignment_submissions_graded_by_index ON assignment_submissions(graded_by);

-- Add comments for documentation
COMMENT ON TABLE assignment_submissions IS 'Stores student submissions for assignments';
COMMENT ON COLUMN assignment_submissions.assignment_id IS 'The assignment this submission is for';
COMMENT ON COLUMN assignment_submissions.user_id IS 'The student who submitted this';
COMMENT ON COLUMN assignment_submissions.submission_text IS 'Text content of the submission';
COMMENT ON COLUMN assignment_submissions.attachment_url IS 'URL to submitted file attachment';
COMMENT ON COLUMN assignment_submissions.submitted_at IS 'When the assignment was submitted';
COMMENT ON COLUMN assignment_submissions.grade IS 'Grade/points awarded';
COMMENT ON COLUMN assignment_submissions.feedback IS 'Teacher feedback on the submission';
COMMENT ON COLUMN assignment_submissions.graded_at IS 'When the submission was graded';
COMMENT ON COLUMN assignment_submissions.graded_by IS 'The teacher who graded this submission';
