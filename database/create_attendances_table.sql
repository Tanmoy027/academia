-- Attendances Table
-- This table stores attendance records for students in courses
-- Teachers can mark attendance for regular classes, make-up classes, and quizzes

CREATE TABLE IF NOT EXISTS attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    type VARCHAR(20) NOT NULL DEFAULT 'regular', -- regular, makeup, quiz
    status VARCHAR(20) NOT NULL DEFAULT 'absent', -- present, absent, late, excused
    notes TEXT NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    UNIQUE(user_id, course_id, date, type)
);

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS attendances_user_id_index ON attendances(user_id);
CREATE INDEX IF NOT EXISTS attendances_course_id_index ON attendances(course_id);
CREATE INDEX IF NOT EXISTS attendances_date_index ON attendances(date);
CREATE INDEX IF NOT EXISTS attendances_type_index ON attendances(type);
CREATE INDEX IF NOT EXISTS attendances_status_index ON attendances(status);

-- Add comments for documentation
COMMENT ON TABLE attendances IS 'Stores attendance records for students in courses';
COMMENT ON COLUMN attendances.user_id IS 'Student who the attendance record belongs to';
COMMENT ON COLUMN attendances.course_id IS 'Course for which attendance is being marked';
COMMENT ON COLUMN attendances.date IS 'Date of the class/quiz';
COMMENT ON COLUMN attendances.type IS 'Type of attendance: regular (regular class), makeup (make-up class), quiz (quiz attendance)';
COMMENT ON COLUMN attendances.status IS 'Attendance status: present, absent, late, or excused';
COMMENT ON COLUMN attendances.notes IS 'Optional notes about the attendance (e.g., reason for absence)';
